const errors = new WeakMap<Page, string[]>()
test.beforeEach(async ({ page }) => { errors.set(page, []); page.on('pageerror', error => errors.get(page)!.push(error.message)); await page.goto('/') })
test.afterEach(async ({ page }) => { expect(errors.get(page)).toEqual([]) })
async function current(page: Page) { return JSON.parse((await page.getByTestId('live-json').textContent())!) }
async function importConfig(page: Page, value: unknown) {
  await page.getByRole('button', { name: 'Import', exact: true }).click()
  await page.getByRole('textbox', { name: 'Import JSON draft' }).fill(JSON.stringify(value, null, 2))
  await page.getByRole('button', { name: 'Apply JSON import' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
}
async function drag(page: Page, from: Locator, to: Locator) {
  await from.scrollIntoViewIfNeeded()
  const start = (await from.boundingBox())!
  await page.mouse.move(start.x + start.width / 2, start.y + start.height / 2)
  await page.mouse.down()
  await page.mouse.move(start.x + start.width / 2 + 10, start.y + start.height / 2 + 10, { steps: 3 })
  await expect(page.locator('.drag-overlay')).toBeVisible()
  await to.scrollIntoViewIfNeeded()
  const end = (await to.boundingBox())!
  await page.mouse.move(end.x + end.width / 2, end.y + end.height / 2, { steps: 15 })
  await expect(to).toHaveClass(/drop-(accepted|rejected)/)
  await page.mouse.up()
  await expect(page.locator('.drag-overlay')).toHaveCount(0)
}
async function design(page: Page) { await page.getByRole('button', { name: 'Design', exact: true }).click() }
async function configuration(page: Page) { await page.getByRole('button', { name: /^JSON \/ checks/ }).click() }
async function rootPalette(page: Page) { await page.getByRole('button', { name: 'Back to main layout', exact: true }).click() }
async function placeButton(page: Page, name: string, destinationPart?: string) {
  await page.locator('.palette-panel').getByRole('button', { name: `Add ${name}`, exact: true }).click()
  if (destinationPart) {
    const option = await page.locator('#destination option').filter({ hasText: destinationPart }).first().getAttribute('value')
    expect(option).toBeTruthy()
    await page.locator('#destination').selectOption(option!)
  }
  await page.getByRole('button', { name: 'Insert component', exact: true }).click()
}

