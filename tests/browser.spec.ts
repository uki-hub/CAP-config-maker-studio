test('unknown/unsupported imports and literal false/zero/null survive editing, download and reimport', async ({ page }) => {
  await page.getByRole('button', { name: 'Import', exact: true }).click()
  const originalText = JSON.stringify(preservation, null, 2)
  await page.getByLabel('Choose import file', { exact: true }).setInputFiles({ name: 'SYNTHETIC-preservation.json', mimeType: 'application/json', buffer: Buffer.from(originalText) })
  await expect(page.getByRole('textbox', { name: 'Import JSON draft' })).toHaveValue(originalText)
  await page.getByRole('button', { name: 'Apply JSON import' }).click()
  expect(await current(page)).toEqual(preservation)
  await expect(page.locator('[data-node-path="$.form.bodySections[0][1]"]')).toContainText('raw preserved node')
  await page.getByRole('button', { name: 'Select Synthetic only', exact: true }).click()
  const payload = page.getByRole('textbox', { name: 'Property $payload', exact: true })
  await payload.fill('{broken')
  expect(await current(page)).toEqual(preservation)
  await expect(page.getByRole('button', { name: 'Apply JSON value' })).toBeDisabled()
  await payload.fill(JSON.stringify({ ...preservation.form.actions[0].$payload, added: [0, false, null] }))
  await page.getByRole('button', { name: 'Apply JSON value' }).click()
  const expected = await current(page)
  expect(expected.form.actions[0].$payload.false).toBe(false)
  expect(expected.form.actions[0].$payload.zero).toBe(0)
  expect(expected.form.actions[0].$payload.null).toBeNull()
  expect(expected.unknownRoot).toEqual(preservation.unknownRoot)
  expect(expected.var).toEqual(preservation.var)
  await configuration(page)
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Draft JSON', exact: true }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toBe('cap-config.draft.json')
  const text = await readFile((await download.path())!, 'utf8')
  expect(JSON.parse(text)).toEqual(expected)
  await importConfig(page, JSON.parse(text))
  expect(await current(page)).toEqual(expected)
  await configuration(page)
  await page.getByRole('tab', { name: /^Checks/ }).click()
  await expect(page.locator('.json-panel')).toContainText('$.form.actions[0].$payload.false')
  await expect(page.locator('.json-panel')).toContainText('R-dispatch')
})

