test('undo and redo recover a completed drag without changing imported values', async ({ page }) => {
  await importConfig(page, supported)
  const before = await current(page)
  await page.getByRole('button', { name: 'Add empty row to Form fields', exact: true }).click()
  const withRow = await current(page)
  await drag(page, page.getByRole('button', { name: 'Drag Reference', exact: true }), page.locator('[data-row-path="$.form.detailSections[0][0].fields[1]"] .drop-area'))
  const moved = await current(page)
  await page.getByRole('button', { name: 'Undo change', exact: true }).click()
  expect(await current(page)).toEqual(withRow)
  await page.getByRole('button', { name: 'Redo change', exact: true }).click()
  expect(await current(page)).toEqual(moved)
  await page.keyboard.press('Control+z')
  expect(await current(page)).toEqual(withRow)
  await page.keyboard.press('Control+z')
  expect(await current(page)).toEqual(before)
  await expect(page.getByRole('button', { name: 'Undo change', exact: true })).toBeDisabled()
})
